# =========================================================
# COMPOSITE SCORES
# =========================================================

# DIGITAL FATIGUE SCORE
df['Fatigue'] = df[

    ['Brain rot', 'AI slop', 'Doomscrolling']

].mean(axis=1)

# NOSTALGIA SCORE
df['Nostalgia'] = df[

    ['Film Camera',
     'Vintage',
     'Retro style',
     'Y2K aesthetic',
     '2000s']

].mean(axis=1)

# =========================================================
# DIGITAL FATIGUE VS NOSTALGIA
# =========================================================

# ---------------------------------------------------------
# PLOT : FATIGUE VS NOSTALGIA
# ---------------------------------------------------------

plt.figure(figsize=(7,7))

plt.plot(

    df['Time'],
    df['Fatigue'],

    label='Digital Fatigue'
)

plt.plot(

    df['Time'],
    df['Nostalgia'],

    label='Nostalgia'
)

# ---------------------------------------------------------
# LABELS
# ---------------------------------------------------------

plt.legend()

plt.xlabel("Year")

plt.ylabel("Trend Score")

plt.title(
    "Digital Fatigue vs Nostalgia Trends"
)

