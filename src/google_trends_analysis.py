plt.savefig(
    "fatigue_vs_nostalgia.png",
    bbox_inches='tight'
)

plt.show()

# =========================================================
# LAG CORRELATION ANALYSIS
# =========================================================

print("\nLag Correlation Results:\n")

lag_results = {}

# Check lag from 0 to 6 months
for lag in range(0, 7):

    shifted_nostalgia = df[
        'Nostalgia'
    ].shift(-lag)

    corr = df[
        'Fatigue'
    ].corr(
        shifted_nostalgia
    )

    lag_results[lag] = corr

    print(
        f"{lag} Month Lag Correlation:",
        round(corr, 3)
    )

# =========================================================
# STRONGEST LAG RELATIONSHIP
# =========================================================

best_lag = max(
    lag_results,
    key=lag_results.get
)

best_corr = lag_results[
    best_lag
]

print("\nStrongest Relationship:")

print(
    f"Nostalgia trends respond strongest "
    f"after {best_lag} month(s)"
)

print(
    f"Correlation = {round(best_corr, 3)}"
)

# ---------------------------------------------------------
# PLOT : LAG CORRELATION
# ---------------------------------------------------------

plt.figure(figsize=(8,5))

plt.plot(

    list(lag_results.keys()),

    list(lag_results.values()),

    marker='o'
)

plt.xlabel("Lag (Months)")

plt.ylabel("Correlation")

plt.title(
    "Lag Correlation Between Digital Fatigue and Nostalgia"
)

plt.grid(True)

# SAVE CHART
plt.savefig(
    "lag_correlation.png",
    bbox_inches='tight'
)

plt.show()

# =========================================================
# INTERPRETATION
# =========================================================

print("\nInterpretation:\n")

if best_corr > 0.5:

    print(
        "A strong positive lag relationship "
        "suggests nostalgia trends may rise "
        "after increases in digital fatigue."
    )

elif best_corr > 0.3:

    print(
        "A moderate positive relationship "
        "suggests possible delayed emotional "
        "responses to online overstimulation."
    )

else:

    print(
        "The lag relationship appears weak, "
        "suggesting limited delayed association."
    )

