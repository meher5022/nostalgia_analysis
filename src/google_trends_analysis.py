# =========================================================
# ANALOG VS DIGITAL NOSTALGIA
# =========================================================

# DIGITAL FATIGUE
df['Digital_Fatigue'] = (

    df[['Brain rot',
        'AI slop',
        'Doomscrolling']]

    .mean(axis=1)
)

# ANALOG NOSTALGIA
df['Analog_Nostalgia'] = (

    df[['Film Camera',
        'Vintage',
        'Retro style']]

    .mean(axis=1)
)

# DIGITAL NOSTALGIA
df['Digital_Nostalgia'] = (

    df[['Y2K aesthetic',
        '2000s']]

    .mean(axis=1)
)

# Extract Year
df['Year'] = df[
    'Time'
].dt.year

# Calculate yearly averages
yearly = df.groupby('Year')[

    ['Digital_Fatigue',
     'Analog_Nostalgia',
     'Digital_Nostalgia']

].mean()

# Calculate yearly change
growth = yearly.diff()

# ---------------------------------------------------------
# PLOT : YEARLY CULTURAL TREND CHANGE
# ---------------------------------------------------------

plt.figure(figsize=(14,7))

plt.plot(

    growth.index,

    growth['Digital_Fatigue'],

    label='Digital Fatigue',

    linewidth=3
)

plt.plot(

    growth.index,

    growth['Analog_Nostalgia'],

    label='Analog Nostalgia',

    linewidth=3
)

plt.plot(

    growth.index,

    growth['Digital_Nostalgia'],

    label='Digital Nostalgia',

    linewidth=3
)

# Zero reference line
plt.axhline(0)

